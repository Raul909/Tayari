"""
Static metadata for each hazard: how to name it, how to draw it, how fast it
arrives, and — importantly — where its numbers come from.

`data_sources` is not decoration. A warning system that cannot say where a claim
came from is asking for trust it has not earned, so every card Tayari renders
carries its provenance down to the reader.
"""

from app.models.hazards import HazardType, Onset


class HazardMeta:
    __slots__ = (
        "hazard", "label", "short_label", "icon", "color", "onset",
        "lead_time", "description", "data_sources", "forecastable",
    )

    def __init__(
        self,
        hazard: HazardType,
        label: str,
        short_label: str,
        icon: str,
        color: str,
        onset: Onset,
        lead_time: str,
        description: str,
        data_sources: list[str],
        forecastable: bool,
    ):
        self.hazard = hazard
        self.label = label
        self.short_label = short_label
        self.icon = icon
        self.color = color
        self.onset = onset
        self.lead_time = lead_time
        self.description = description
        self.data_sources = data_sources
        # False for hazards nobody can forecast (earthquakes). Their card is
        # about preparedness and recent activity, never about prediction — and
        # the UI needs to know the difference so it never implies otherwise.
        self.forecastable = forecastable


