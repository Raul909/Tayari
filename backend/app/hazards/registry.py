def meta(hazard: HazardType) -> HazardMeta:
    return HAZARD_META[hazard]


def catalog() -> list[dict]:
    """Serializable hazard catalog for the API and the client."""
    return [
        {
            "hazard": m.hazard.value,
            "label": m.label,
            "short_label": m.short_label,
            "icon": m.icon,
            "color": m.color,
            "onset": m.onset.value,
            "lead_time": m.lead_time,
            "description": m.description,
            "data_sources": m.data_sources,
            "forecastable": m.forecastable,
        }
        for m in HAZARD_META.values()
    ]
